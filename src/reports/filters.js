// Report filters — the one place a reporting querystring becomes SQL.
//
// Every Epic 5 report is a date range first and a narrowing second, and the
// table and its CSV export share one query builder (US-006) so the two cannot
// disagree about what was filtered. That makes this the single boundary where a
// caller's values are checked, and it is deliberately PURE — no pool, no query,
// nothing to stub — so the whitelist and the placeholder discipline are
// unit-testable on their own (test/report-filters.test.js).
//
// Two rules it exists to enforce:
//   - a filter NAME resolves through a frozen whitelist to a trusted column
//     literal. An unrecognised name is ignored, exactly as the public catalogue
//     listing ignores an unknown query param — the whitelist is what controls
//     which filters exist, never the schema's strictness.
//   - a filter VALUE never reaches the SQL text. It is validated into a
//     canonical form here and bound as a $n placeholder by buildReportFilters.
//
// The column literals also fix the table aliases every report query must use:
// `o` orders, `b` brands, `p` products, `col` collections — the same letters the
// order and catalogue read models already carry.

import { ORDER_STATUSES } from '../orders/admin-orders.js'

const httpError = (statusCode, message) =>
  Object.assign(new Error(message), { statusCode })

// Filter name -> the trusted column it constrains. `from` and `to` are two
// bounds on one column, which is why this is a name->column map rather than a
// name->clause one: the clause shape belongs to buildReportFilters below.
export const FILTER_COLUMNS = Object.freeze({
  from: 'o.created_at',
  to: 'o.created_at',
  brand: 'b.slug',
  product_type: 'p.product_type',
  collection: 'col.slug',
  kind: 'o.kind',
  status: 'o.status',
})

export const REPORT_FILTER_NAMES = Object.freeze(Object.keys(FILTER_COLUMNS))

// Boundary copies of the database CHECK constraints, in the posture
// DISCOUNT_METHOD_ENUM takes in src/routes/admin-suppliers.js: without them an
// unknown value reaches the CHECK and surfaces as a 500 instead of a 400, and
// with them the two can drift — so test/admin-reports.test.js parses the live
// pg_get_constraintdef and asserts each set matches.
export const PRODUCT_TYPES = Object.freeze(['fabric', 'finished_good'])
export const ORDER_KINDS = Object.freeze([
  'checkout',
  'order_request',
  'backorder_request',
  'manual',
])

// `status` deliberately reuses the orders module's own frozen list rather than
// retyping it. It is already what /admin/orders validates against, and
// architecture.md § Reporting says the revenue default becomes a change to one
// frozen constant when the client settles A2 — a second copy is how that turns
// into two decisions.
export { ORDER_STATUSES }

const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/
// Slugs are generated by src/seed/slugify.js, so they are [a-z0-9-] by
// construction. Validating the shape means a mistyped filter is a 400 naming it
// rather than a report that silently matches nothing.
const SLUG_PATTERN = /^[a-z0-9-]+$/

// Values are echoed back so the office can see what it typed; capped so a long
// query param cannot turn an error message into a payload.
const PREVIEW_LIMIT = 60
const preview = (value) => {
  const text = typeof value === 'string' ? value : JSON.stringify(value) ?? String(value)
  return text.length > PREVIEW_LIMIT ? `${text.slice(0, PREVIEW_LIMIT)}…` : text
}

const invalid = (name, value, expected) =>
  httpError(400, `Invalid value for filter "${name}" (${preview(value)}): expected ${expected}.`)

const isBlank = (value) =>
  value === undefined || value === null || (typeof value === 'string' && value.trim() === '')

const textOf = (name, value) => {
  if (typeof value !== 'string') {
    throw invalid(name, value, 'a text value')
  }
  return value.trim()
}

// A calendar date, not a timestamp: the CRM's date inputs produce YYYY-MM-DD and
// a report range is a range of days. The round trip is what rejects 2026-02-30,
// which the regex alone accepts.
const parseDate = (name, value) => {
  const text = textOf(name, value)
  if (!DATE_PATTERN.test(text)) {
    throw invalid(name, text, 'a calendar date as YYYY-MM-DD')
  }
  const parsed = new Date(`${text}T00:00:00Z`)
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== text) {
    throw invalid(name, text, 'a real calendar date as YYYY-MM-DD')
  }
  return text
}

const parseEnum = (name, value, allowed) => {
  const text = textOf(name, value)
  if (!allowed.includes(text)) {
    throw invalid(name, text, `one of ${allowed.join(', ')}`)
  }
  return text
}

const parseSlug = (name, value) => {
  const text = textOf(name, value)
  if (!SLUG_PATTERN.test(text)) {
    throw invalid(name, text, 'a slug of lowercase letters, digits and hyphens')
  }
  return text
}

// `brand` is the one multi-valued filter: the office compares houses against
// each other, and a report of one house at a time is a different question.
// Repeated params (brand=a&brand=b) and one comma-separated value are both
// accepted because the two arrive from the CRM and from a hand-typed URL
// respectively. A wholly empty value is absent, never "match nothing".
const parseSlugList = (name, value) => {
  const entries = (Array.isArray(value) ? value : [value])
    .flatMap((entry) => (typeof entry === 'string' ? entry.split(',') : [entry]))
    .filter((entry) => !isBlank(entry))
  if (entries.length === 0) {
    return undefined
  }
  const slugs = entries.map((entry) => parseSlug(name, entry))
  return Object.freeze([...new Set(slugs)])
}

const PARSERS = Object.freeze({
  from: (value) => parseDate('from', value),
  to: (value) => parseDate('to', value),
  brand: (value) => parseSlugList('brand', value),
  product_type: (value) => parseEnum('product_type', value, PRODUCT_TYPES),
  collection: (value) => parseSlug('collection', value),
  kind: (value) => parseEnum('kind', value, ORDER_KINDS),
  status: (value) => parseEnum('status', value, ORDER_STATUSES),
})

// Every column is a code literal naming an alias and a column, checked here so a
// typo throws while the module loads rather than reaching SQL — the posture
// assertEntity (src/lifecycle/registry.js) and assertStorable take.
const COLUMN_REFERENCE = /^[a-z]+\.[a-z_]+$/
for (const [name, column] of Object.entries(FILTER_COLUMNS)) {
  if (!COLUMN_REFERENCE.test(column)) {
    throw new Error(`Report filter "${name}" has a malformed column reference: ${column}`)
  }
  if (!Object.hasOwn(PARSERS, name)) {
    throw new Error(`Report filter "${name}" has no parser`)
  }
}

/**
 * Validates a querystring into the canonical filter object the report builders
 * take. Unknown keys are ignored; a recognised key carrying an unusable value
 * is a 400 naming the filter.
 *
 * @param {object} [query]
 * @returns {Readonly<object>} only the filters actually supplied
 */
export const parseReportFilters = (query = {}) => {
  const filters = {}

  for (const name of REPORT_FILTER_NAMES) {
    const raw = query?.[name]
    if (isBlank(raw)) continue
    const value = PARSERS[name](raw)
    // parseSlugList returns undefined for a list that was blank throughout.
    if (value !== undefined) {
      filters[name] = value
    }
  }

  // A backwards range is a mistake with an empty report as its symptom, so it is
  // refused rather than answered with zero rows.
  if (filters.from && filters.to && filters.from > filters.to) {
    throw httpError(
      400,
      `Invalid report range: "from" (${filters.from}) is after "to" (${filters.to}).`
    )
  }

  return Object.freeze(filters)
}

// One clause per filter. `column` is trusted; `index` is the placeholder number
// the caller's params array has just reached.
const CLAUSES = Object.freeze({
  from: (column, index) => `${column} >= $${index}::date`,
  // Inclusive: a `to` of today must carry today's orders. `<= $n::date` would cut
  // the range at that morning's midnight and silently drop the whole day.
  to: (column, index) => `${column} < ($${index}::date + 1)`,
  brand: (column, index) => `${column} = ANY($${index}::text[])`,
  product_type: (column, index) => `${column} = $${index}`,
  collection: (column, index) => `${column} = $${index}`,
  kind: (column, index) => `${column} = $${index}`,
  status: (column, index) => `${column} = $${index}`,
})

/**
 * Split supplied filters into the ones a report can honour and the ones it
 * cannot.
 *
 * A report declines a filter by leaving it out of `names` — the stock report is
 * a snapshot with no `orders` in its FROM, so a date range there is a question
 * it has no way to answer. Declining is deliberately not a 400: the CRM drives
 * every report from ONE filter bar, so a date range left in the bar would
 * otherwise refuse the report the moment it was selected. What it must never be
 * is silent — an ignored filter that still appeared in `meta.filters` would be
 * echoed into the CSV's own notes as if it had narrowed the file.
 *
 * @param {object} [filters] output of parseReportFilters
 * @param {readonly string[]} [names] the filters this report honours
 * @returns {{ honoured: Readonly<object>, ignored: readonly string[] }}
 */
export const partitionFilters = (filters = {}, names = REPORT_FILTER_NAMES) => {
  const honoured = {}
  const ignored = []

  for (const name of REPORT_FILTER_NAMES) {
    if (filters[name] === undefined || filters[name] === null) continue
    if (names.includes(name)) {
      honoured[name] = filters[name]
    } else {
      ignored.push(name)
    }
  }

  return { honoured: Object.freeze(honoured), ignored: Object.freeze(ignored) }
}

/**
 * Turns parsed filters into WHERE fragments and bound params.
 *
 * `params` lets a report append its filters to placeholders it has already
 * bound; the array is copied, never mutated. `names` is how a report that
 * cannot honour a filter says so — the stock report has no `orders` in its FROM,
 * so a `status` clause there would be a broken query rather than a narrowing.
 *
 * @param {object} [filters] output of parseReportFilters
 * @param {{ params?: unknown[], names?: readonly string[] }} [options]
 * @returns {{ clauses: string[], params: unknown[], where: string }}
 */
export const buildReportFilters = (filters = {}, { params = [], names } = {}) => {
  const allowed = names ?? REPORT_FILTER_NAMES
  for (const name of allowed) {
    // A code literal, like a lifecycle registry key: an unknown one is a bug in
    // the report, not a client mistake, so it throws rather than 400s.
    if (!Object.hasOwn(FILTER_COLUMNS, name)) {
      throw new Error(`Unknown report filter: ${name}`)
    }
  }

  const bound = [...params]
  const clauses = []

  // REPORT_FILTER_NAMES order, not the caller's key order, so one filter set
  // always produces one SQL string.
  for (const name of REPORT_FILTER_NAMES) {
    if (!allowed.includes(name)) continue
    const value = filters[name]
    if (value === undefined || value === null) continue
    bound.push(Array.isArray(value) ? [...value] : value)
    clauses.push(CLAUSES[name](FILTER_COLUMNS[name], bound.length))
  }

  return { clauses, params: bound, where: clauses.join(' AND ') }
}
